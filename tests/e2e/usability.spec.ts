test('failed card addition retains selection and never reports success before a saved retry', async ({ page }) => {
  await ready(page); await create(page, 'Retry adding');
  await page.getByRole('link', { name: 'Library', exact: true }).click();
  await page.getByRole('link', { name: 'Card browser', exact: true }).click();
  const card = page.getByRole('button', { name: 'Select card: ' + prompt, exact: true });
  await card.click();
  await page.evaluate(() => {
    const original = IDBObjectStore.prototype.add;
    let fail = true;
    IDBObjectStore.prototype.add = function(value, key) {
      if (fail && this.name === 'copies') { fail = false; throw new DOMException('Simulated card addition failure', 'QuotaExceededError'); }
      return original.call(this, value, key);
    };
  });
  const add = page.getByRole('button', { name: 'Add selected cards (1)', exact: true });
  await add.click();
  await expect(page.getByRole('alert').first()).toContainText('could not be saved');
  await expect(page.locator('.library-destination > .library-operation-feedback')).toHaveText('');
  await expect(card).toHaveAttribute('aria-pressed', 'true');
  await expect(add).toBeEnabled();
  expect(await rows(page, 'copies')).toHaveLength(0);
  await add.click();
  await expect(page.locator('.library-destination > .library-operation-feedback')).toContainText('Added 1 card to “Retry adding”.');
  await expect(card).toHaveAttribute('aria-pressed', 'false');
  await expect(card.locator('.library-membership')).toContainText('In Retry adding');
  expect(await rows(page, 'copies')).toHaveLength(1);
});


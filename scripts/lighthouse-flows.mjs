import fs from 'node:fs/promises';
import path from 'node:path';
import net from 'node:net';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import {chromium, expect} from '@playwright/test';
// Pass the cached lighthouse@13.6.0 package directory; no runtime app dependency is added.
const lighthousePath = path.resolve(process.argv[2] ?? 'node_modules/lighthouse');
const require = createRequire(path.join(lighthousePath,'package.json'));
const puppeteer = require('puppeteer-core');
const launcher = require('chrome-launcher');
const freePort = () => new Promise((resolve,reject)=>{const server=net.createServer();server.once('error',reject);server.listen(0,'127.0.0.1',()=>{const port=server.address().port;server.close(()=>resolve(port));});});
const {startFlow} = await import(pathToFileURL(path.join(lighthousePath,'core/index.js')).href);
// Tests show five questions a page, so a multiple-answer question may be further on.
const unrevealedMultiple = async page => {
  for (;;) {
    const found = page.locator('.test-question:not(:has(.test-answer))').filter({has:page.getByRole('checkbox')}).first();
    if (await found.count()) return found;
    await page.getByRole('button',{name:'Next page',exact:true}).click();
  }
};
const chromePath = path.join(process.env['ProgramFiles(x86)'], 'Microsoft/Edge/Application/msedge.exe');
await fs.mkdir('reports/lighthouse',{recursive:true});
for (const [theme,width] of [['dark',1440],['light',390]]) {
  const chrome=await launcher.launch({chromePath,port:await freePort(),chromeFlags:['--headless','--no-first-run']});
  const browser=await puppeteer.connect({browserURL:'http://127.0.0.1:'+chrome.port});
  try {
    const auditPage=await browser.newPage();
    // These flows exercise the engineering fixtures, which learners only see behind this flag.
    await auditPage.evaluateOnNewDocument(()=>localStorage.setItem('tsukiakari.showFixtures','on'));
    await auditPage.goto('http://localhost:4187/');
    const driver=await chromium.connectOverCDP(browser.wsEndpoint());
    const page=driver.contexts()[0].pages().find(item=>item.url().startsWith('http://localhost:4187/'));
    if (!page) throw new Error('Audit page not found');
    await page.setViewportSize({width,height:1000});
    // Reuse the already-loaded audit page; a second immediate navigation can race writer-lock cleanup.
    await expect(page.getByText('Saved in this browser',{exact:true}).first()).toBeVisible();
    await page.getByRole('link',{name:'Settings',exact:true}).click();
    await page.getByLabel('Appearance',{exact:true}).selectOption(theme);
    const flow=await startFlow(auditPage,{name:'Populated '+theme+' '+width+'px',config:{extends:'lighthouse:default',settings:{onlyCategories:['accessibility','best-practices'],screenEmulation:{disabled:true},formFactor:width<900?'mobile':'desktop'}}});
    const capture=async name=>{console.log('Auditing '+theme+' '+name);if(auditPage.url()!==page.url() || !auditPage.url().startsWith('http://localhost:4187/')) throw new Error('Audit target mismatch');await flow.snapshot({name});};
    await page.getByRole('link',{name:'Study',exact:true}).click();
    await page.getByRole('button',{name:'Create a deck',exact:true}).click();
    const create=page.getByRole('dialog',{name:'Create a deck',exact:true});
    await create.getByLabel('Deck name',{exact:true}).fill('Lighthouse fixture deck');
    await create.getByRole('button',{name:'Create deck',exact:true}).click();
    await expect(create).not.toBeVisible();
    await page.getByRole('link',{name:'Library',exact:true}).click();
    await page.getByLabel('Destination deck',{exact:true}).selectOption({label:'Lighthouse fixture deck'});
    const pack=page.locator('.library-pack').filter({has:page.getByRole('heading',{name:'Foundation fixtures',exact:true})});
    await pack.getByRole('button',{name:'Add entire pack',exact:true}).click();
    await expect(pack.getByRole('button',{name:'All pack cards added',exact:true})).toBeDisabled();
    await page.getByRole('link',{name:'Study',exact:true}).click();
    await page.getByRole('button',{name:'Study Lighthouse fixture deck',exact:true}).click();
    const choices=page.getByRole('radiogroup',{name:'Answer choices'});
    if(await choices.count())await choices.getByRole('radio').first().click();
    await page.getByRole('button',{name:'Reveal answer',exact:true}).click();
    await expect(page.getByTestId('revealed-answer')).toBeVisible();
    await capture('Revealed flashcard');
    await page.getByRole('button',{name:'Again',exact:true}).click();
    await expect(page.locator('.save-status')).toContainText('Saved in this browser');
    await page.getByRole('link',{name:'Library',exact:true}).click();
    await page.getByRole('link',{name:'Card browser',exact:true}).click();
    await page.getByRole('button',{name:'Select card: Fixture: What is 2 + 3?',exact:true}).click();
    const inspector=page.getByRole('region',{name:'Card details',exact:true});
    await inspector.getByRole('tab',{name:'My notes',exact:true}).click();
    await capture('Personal note editor');
    await inspector.getByRole('button',{name:/Close details|Back to cards/}).click();
    await page.getByRole('link',{name:'Notes',exact:true}).click();
    await page.getByRole('button',{name:'Read note: Fixture note: combining quantities',exact:true}).click();
    await capture('Published note document');
    const published=JSON.parse(await fs.readFile('src/content/published/study-pack.json','utf8'));
    for(const [noteId,label] of [['cc-d1-n03','Deployment rollout note'],['cc-d1-n07','Roles and personas note'],['cc-d2-n03','Chat configuration note'],['cc-d2-n07','Translation setup note'],['cc-d1-n09','CRM synchronization note'],['cc-d2-n09','Record channel note'],['cc-d2-n16','Voice architecture note'],['cc-d2-n23','Outbound engagement note'],['cc-d3-n03','AI assistance note'],['cc-d4-n03','Queue routing note'],['cc-d5-n03','Representative experience note'],['cc-d6-n03','Supervisor configuration note']]) {
      const back=page.getByRole('button',{name:'← Back to notes',exact:true});
      if(await back.isVisible())await back.click();
      await page.getByRole('button',{name:'Read note: '+published.notes.find(note=>note.id===noteId).title,exact:true}).click();
      await capture(label);
    }
    await page.getByRole('link',{name:'Statistics',exact:true}).click();
    await page.getByLabel('Topic study pack',{exact:true}).selectOption('developer-foundation-fixture');
    await page.getByRole('region',{name:'Flashcard topics',exact:true}).scrollIntoViewIfNeeded();
    await capture('Saved flashcard topic summary');
    await page.getByRole('link',{name:'Tests',exact:true}).click();
    await page.getByLabel('Question bank',{exact:true}).selectOption('developer-test-fixture');
    await page.getByRole('button',{name:'Start practice',exact:true}).click();
    await expect(page.locator('.test-question')).toHaveCount(5);
    await page.locator('.test-question').first().locator('input[type=radio], input[type=checkbox]').first().check();
    await expect(page.locator('.save-status')).toContainText('Saved in this browser');
    await page.locator('.test-question').first().getByRole('button',{name:'Reveal answer',exact:true}).click();
    await expect(page.locator('.test-answer').first()).toBeVisible();
    await capture('100-question practice with revealed answer');
    const multiple = await unrevealedMultiple(page);
    await multiple.scrollIntoViewIfNeeded();
    await multiple.getByRole('checkbox').first().check();
    await expect(page.locator('.save-status')).toContainText('Saved in this browser');
    await capture('Multiple-answer question');
    await page.getByRole('button',{name:'Back to Tests',exact:true}).click();
    page.once('dialog',dialog=>dialog.accept());
    await page.getByRole('region',{name:'Unfinished test',exact:true}).getByRole('button',{name:'Abandon test',exact:true}).click();
    await page.getByLabel('Question bank',{exact:true}).selectOption('ab250-original');
    await expect(page.getByText(/300 available questions/)).toBeVisible();
    await page.getByRole('button',{name:'Start practice',exact:true}).click();
    await expect(page.locator('.test-question')).toHaveCount(5);
    await page.locator('.test-question').first().getByRole('button',{name:'Reveal answer',exact:true}).click();
    await expect(page.locator('.test-answer').first()).toBeVisible();
    await capture('Original AB-250 practice with sourced explanation');
    const realMultipleTitleId=await (await unrevealedMultiple(page)).getByRole('heading',{level:2}).getAttribute('id');
    if(!realMultipleTitleId)throw new Error('Missing stable question title');
    // Keep the same question after reveal removes it from the unrevealed candidate set.
    const realMultiple=page.locator('.test-question').filter({has:page.locator('[id="'+realMultipleTitleId+'"]')});
    await realMultiple.scrollIntoViewIfNeeded();
    await realMultiple.getByRole('checkbox').first().check();
    await expect(page.locator('.save-status')).toContainText('Saved in this browser');
    await realMultiple.getByRole('button',{name:'Reveal answer',exact:true}).click();
    await expect(realMultiple.getByRole('heading',{name:'Why these choices?',exact:true})).toBeVisible();
    await capture('Original multiple-answer explanation');
    await realMultiple.locator('.test-learning-resources > summary').click();
    await capture('Question study resources');
    await realMultiple.locator('.test-learning-resources a').first().click();
    await expect(page.getByRole('region',{name:'Note reader',exact:true})).toBeVisible();
    await capture('Linked note from practice');
    await page.goBack();
    await expect(page.locator('.test-question')).toHaveCount(5);
    page.once('dialog',dialog=>dialog.accept());
    await page.getByRole('button',{name:'Abandon test',exact:true}).click();
    await page.getByLabel('Test mode',{exact:true}).selectOption('exam');
    await page.getByRole('button',{name:'Start exam',exact:true}).click();
    await expect(page.locator('.test-question')).toHaveCount(5);
    await capture('Original 100-question timed exam');
    page.once('dialog',dialog=>dialog.accept());
    await page.getByRole('button',{name:'Finish test',exact:true}).click();
    const resultDialog=page.getByRole('dialog',{name:'Test results',exact:true});
    await expect(resultDialog).toBeVisible();
    await capture('Original exam results dialog');
    await resultDialog.getByRole('button',{name:'Review exam',exact:true}).click();
    await expect(page.locator('.test-answer')).toHaveCount(100);
    await capture('Original exam review with references');
    const domainResults=page.getByRole('region',{name:'Results by domain',exact:true});
    await domainResults.scrollIntoViewIfNeeded();
    await capture('Frozen exam domain outcomes');
    const domainResources=domainResults.locator('.test-learning-resources').first();
    await domainResources.locator(':scope > summary').click();
    await domainResources.locator('.test-resource-cards > summary').click();
    await capture('Domain study resources');
    await domainResources.locator('.test-resource-cards a').first().click();
    await expect(page.getByRole('region',{name:'Card details',exact:true})).toBeVisible();
    await capture('Linked card inspector from exam');
    await page.goBack();
    await expect(domainResults).toBeVisible();
    await expect(page.getByRole('dialog',{name:'Test results',exact:true})).toHaveCount(0);
    await capture('Returned frozen exam review');
    const result=await flow.createFlowResult();
    await fs.writeFile('reports/lighthouse/populated-'+theme+'.json',JSON.stringify(result,null,2));
    await fs.writeFile('reports/lighthouse/populated-'+theme+'.html',await flow.generateReport());
    console.log(JSON.stringify(result.steps.map(step=>({name:step.name,scores:Object.fromEntries(Object.entries(step.lhr.categories).map(([k,v])=>[k,v.score]))}))));
  } finally { await browser.close(); await chrome.kill(); }
}
